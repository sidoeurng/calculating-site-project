    // មុខងារថ្មីសម្រាប់ QR Code
    function handleQrCodeUpload(file) {
        if (!file) {
            localStorage.removeItem('qrCodeImage');
            return;
        }

        const reader = new FileReader();
        reader.onload = (e) => {
            // រក្សាទុក base64 string ក្នុង local storage
            saveInput('qrCodeImage', e.target.result);
        };
        reader.readAsDataURL(file);
    }

