    function calculateRow(row) {
        const qtyInput = row.querySelector('.item-qty');
        const priceInput = row.querySelector('.item-price');
        const totalCell = row.querySelector('.item-total');

        const qty = parseFloat(qtyInput.value) || 0;
        const price = parseFloat(priceInput.value) || 0;
        
        let total = qty * price;
        total = Math.round(total * 100) / 100;

        totalCell.textContent = formatCurrency(total);
        calculateAllRows();
    }

    function calculateAllRows() {
        let grandTotal = 0;
        const rows = document.querySelectorAll('#invoiceBody .item-row');
        
        rows.forEach(row => {
            const qty = parseFloat(row.querySelector('.item-qty').value) || 0;
            const price = parseFloat(row.querySelector('.item-price').value) || 0;
            
            let total = qty * price;
            total = Math.round(total * 100) / 100;
            
            grandTotal += total;
            
            row.querySelector('.item-total').textContent = formatCurrency(total); 
        });

        grandTotal = Math.round(grandTotal * 100) / 100;

        document.getElementById('grandTotal').innerHTML = `${formatCurrency(grandTotal)}`;
    }

    function addItem() {
        const invoiceBody = document.getElementById('invoiceBody');
        const newRow = document.createElement('tr');
        newRow.classList.add('item-row');
        newRow.innerHTML = `
            <td class="text-center serial-number"></td>
            <td><input type="text" class="form-control item-name" required data-lang-placeholder-key="placeholder_item_name"></td>
            <td><input type="number" class="form-control item-qty text-center" value="1" min="1" oninput="calculateRow(this.closest('.item-row'))"></td>
            <td><input type="number" class="form-control item-price text-end" value="0" min="0" step="0.01" oninput="calculateRow(this.closest('.item-row'))"></td>
            <td class="text-end item-total">${formatCurrency(0)}</td>
            <td class="no-print text-center"><button type="button" class="btn btn-danger btn-sm remove-item" onclick="removeItem(this.closest('.item-row'))"><i class="fas fa-trash-alt"></i></button></td>
        `;
        invoiceBody.appendChild(newRow);
        updateSerialNumbers();
        calculateAllRows(); 
        translatePlaceholders(newRow);
    }

    function removeItem(row) {
        const rows = document.querySelectorAll('#invoiceBody .item-row');
        if (rows.length <= 1) {
            alert(translations['alert_min_item'][currentLang] || "You cannot delete all items. There must be at least one item.");
            return;
        }
        row.remove();
        updateSerialNumbers();
        calculateAllRows(); 
    }
    
    function updateSerialNumbers() {
        const rows = document.querySelectorAll('#invoiceBody .item-row');
        rows.forEach((row, index) => {
            row.querySelector('.serial-number').textContent = index + 1;
        });
    }

