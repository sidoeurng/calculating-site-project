    function formatCurrency(amount) {
        // ប្រើ toLocaleString សម្រាប់ការបំបែកសញ្ញា (,) និងកំណត់ខ្ទង់ទសភាគពីរ (2)
        const formatted = (Math.round(amount * 100) / 100).toLocaleString(currentLang === 'km' ? 'en-US' : currentLang, {
            minimumFractionDigits: 2,
            maximumFractionDigits: 2,
            useGrouping: true // ប្រើសញ្ញា (,)
        });

        // សម្រាប់ KHR គឺដាក់សញ្ញានៅខាងចុង
        if (currencyCode === 'KHR') {
            return `${formatted}${currencySymbol}`;
        }
        // សម្រាប់ USD ឬផ្សេងទៀត គឺដាក់សញ្ញានៅខាងមុខ
        return `${currencySymbol}${formatted}`;
    }
    
    function updateCurrencySymbol(initialLoad = false) {
        const select = document.getElementById('currencySelect');
        const selectedOption = select.options[select.selectedIndex];
        currencySymbol = selectedOption.getAttribute('data-symbol') || '៛';
        currencyCode = selectedOption.value;

        // កែសម្រួល Header នៃតារាង input
        document.getElementById('priceHeader').textContent = translations['col_unit_price'][currentLang] + ` (${currencySymbol})`;
        document.getElementById('totalHeader').textContent = translations['col_total_price'][currentLang] + ` (${currencySymbol})`;

        // គណនាឡើងវិញដើម្បីធ្វើបច្ចុប្បន្នភាពនិមិត្តសញ្ញារូបិយប័ណ្ណ
        calculateAllRows();
    }
    
    function formatDate(date, lang) {
        const day = date.getDate();
        const year = date.getFullYear();
        let monthName;
        
        switch (lang) {
            case 'km':
                monthName = khmerMonths[date.getMonth()];
                return `${day} ${monthName} ឆ្នាំ${year}`;
            case 'zh':
                monthName = chineseMonths[date.getMonth()];
                return `${year}年 ${monthName} ${day}日`;
            case 'en':
            default:
                monthName = englishMonths[date.getMonth()];
                return `${monthName} ${day}, ${year}`;
        }
    }
    
    function translatePlaceholders(container = document) {
        container.querySelectorAll('[data-lang-placeholder-key]').forEach(el => {
            const key = el.getAttribute('data-lang-placeholder-key');
            if (translations[key] && translations[key][currentLang]) {
                el.placeholder = translations[key][currentLang];
            }
        });
    }

    function translatePage(lang) {
        currentLang = lang;
        document.documentElement.lang = lang;
        
        document.querySelectorAll('[data-lang-key]').forEach(el => {
            const key = el.getAttribute('data-lang-key');
            if (translations[key] && translations[key][lang]) {
                el.textContent = translations[key][lang];
            }
        });
        
        translatePlaceholders();
        updateCurrencySymbol(true); 
    }
    
    function downloadInvoiceAsImage(format) {
        const element = document.getElementById('invoiceViewContainer');
        const filename = `${document.getElementById('finalInvoiceNumber').textContent}_invoice.${format}`;
        
        html2canvas(element, {
            scale: 2, // បង្កើនគុណភាពរូបភាព
            useCORS: true,
            logging: false,
            // កាត់ផ្តាច់ធាតុដែលមិនចង់បានពីការចាប់យករូបភាព (ដូចជាប៊ូតុងត្រឡប់)
            ignoreElements: (element) => element.getAttribute('data-html2canvas-ignore') === 'true'
        }).then(canvas => {
            const image = canvas.toDataURL(`image/${format}`, 1.0);
            const link = document.createElement('a');
            link.href = image;
            link.download = filename;
            document.body.appendChild(link);
            link.click();
            document.body.removeChild(link);
        });
    }

